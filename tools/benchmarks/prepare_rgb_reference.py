"""Prepare a separate RGB reference sketch; never edit firmware or installed LVGL."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
PRODUCTION = ROOT / "Module/DisplayModule_800x480"
REFERENCE = Path(__file__).resolve().parent / "DisplayRgbReference"


def panel_class(source):
    start = source.index("class OfeEspLcdRgbDisplay : public Arduino_GFX {")
    end = source.index("\n#if 0", start)
    block = source[start:end].strip()
    if not block.endswith("};"):
        raise ValueError("Unknown production RGB driver boundary")
    return block


def sha(data):
    return hashlib.sha256(data).hexdigest()


def generated_files(lvgl):
    source = (PRODUCTION / (PRODUCTION.name + ".ino")).read_text(encoding="utf-8-sig")
    banner = "// Generated by tools/benchmarks/prepare_rgb_reference.py; do not edit.\n"
    defaults = banner + "#pragma once\n"
    production_defaults = {}
    for name in ("DISPLAY_RGB_WIDTH", "DISPLAY_RGB_HEIGHT", "DISPLAY_RGB_PCLK_HZ",
                 "DISPLAY_RGB_BOUNCE_BUFFER_LINES", "DISPLAY_RGB_INVERT_COLORS", "DISPLAY_ROTATION"):
        values = re.findall(r"^#define " + name + r" (\d+)\s*$", source, re.M)
        if len(values) != 1:
            raise ValueError("Ambiguous production default: " + name)
        defaults += f"#define {name} {values[0]}\n"
        production_defaults[name] = int(values[0])
    outputs = {
        "src/OfeReferenceDefaults.h": defaults.encode(),
        "src/OfeReferencePanel.h": (banner + "#pragma once\n" + panel_class(source) + "\n").encode(),
        "src/OfeRgbTileCopy.h": (PRODUCTION / "src/OfeRgbTileCopy.h").read_bytes(),
        "ofe_reference_base.h": (PRODUCTION / "ofe_lv_conf.h").read_bytes(),
    }
    version = (lvgl / "library.properties").read_text(encoding="utf-8-sig")
    if not re.search(r"^version=9\.6\.", version, re.M):
        raise ValueError("Reference harness is verified for installed LVGL 9.6.x only")
    sites = [lvgl / "demos/lv_demos.c"]
    sites += sorted((lvgl / "demos/benchmark").glob("*.c"))
    sites += sorted((lvgl / "demos/benchmark/assets").glob("img_*.c"))
    sites += sorted((lvgl / "demos/widgets").rglob("*.c"))
    if len(sites) != 14:
        raise ValueError("Installed benchmark source layout changed; review wrappers")
    upstream = {}
    for site in sites:
        rel = site.relative_to(lvgl).as_posix()
        # Arduino compiles library src/, not demos/. Each wrapper uses the
        # installed library's src include root to reach its unchanged demos.
        outputs["src/upstream_" + site.stem + ".c"] = (
            banner + "#include <../" + rel + ">\n").encode()
        upstream[rel] = sha(site.read_bytes())
    manifest = {
        "production_file": (PRODUCTION / (PRODUCTION.name + ".ino")).relative_to(ROOT).as_posix(),
        "production_defaults": production_defaults,
        "production_panel_sha256": sha(panel_class(source).encode()),
        "production_lv_config_sha256": sha(outputs["ofe_reference_base.h"]),
        "upstream_lvgl": "9.6.x",
        "upstream_sources_sha256": upstream,
        "generated_sha256": {name: sha(data) for name, data in outputs.items()},
    }
    outputs["reference-manifest.json"] = (json.dumps(manifest, indent=2) + "\n").encode()
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lvgl", type=Path, default=Path.home() / "Documents/Arduino/libraries/lvgl")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = generated_files(args.lvgl)
    for name, data in outputs.items():
        destination = REFERENCE / name
        if args.check:
            if not destination.exists() or destination.read_bytes() != data:
                raise SystemExit("Reference file is stale: " + name)
        else:
            destination.parent.mkdir(parents=True, exist_ok=True)
            if not destination.exists() or destination.read_bytes() != data:
                destination.write_bytes(data)
    print(f"PASS: {len(outputs)} reference files {'verified' if args.check else 'prepared'}; production/LVGL untouched")


if __name__ == "__main__":
    main()
