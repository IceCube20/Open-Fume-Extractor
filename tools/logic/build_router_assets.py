"""Reproducibly embed the pinned, unmodified libavoid browser distribution."""
import argparse
import gzip
import hashlib
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[2]
VENDOR = ROOT / 'assets/vendor/libavoid'
OUTPUT = ROOT / 'OpenFumeExtractorMaster/OpenFumeExtractorMCU_S3/src/WebLogicRouterAssets.h'
COMMIT = '28a6fe20c2f1f809afdbeca8d789e65357614c4f'
FILES = {
    'index.js': ('dist/index.js', 'f73a026bbb83de097619790cd91b081ca4f5575d'),
    'libavoid.wasm': ('dist/libavoid.wasm', '5043d8771c08f174d6366374ad472c27df2755ae'),
    'LICENSE': ('LICENSE', 'b885a535c6e8726d4ccc275bd1c36bfaad726a1e'),
}


def verified(name, fetch=False):
    relative, expected = FILES[name]
    path = VENDOR / name
    data = urlopen(f'https://raw.githubusercontent.com/Aksem/libavoid-js/{COMMIT}/{relative}', timeout=45).read() if fetch else path.read_bytes()
    blob = hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest()
    if blob != expected:
        raise ValueError('Pinned upstream Git blob mismatch: ' + name)
    if fetch:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fetch', action='store_true', help='Fetch and verify the pinned upstream bytes')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    lines = ['#pragma once', '', '// Generated by tools/logic/build_router_assets.py; do not edit.',
             '// libavoid-js 0.4.5 / libavoid: LGPL-2.1-or-later; see assets/vendor/libavoid.', '']
    for name, symbol in [('index.js', 'JS'), ('libavoid.wasm', 'WASM'), ('LICENSE', 'LICENSE')]:
        compressed = gzip.compress(verified(name, args.fetch), compresslevel=9, mtime=0)
        lines.append(f'static const unsigned char OFE_LOGIC_ROUTER_{symbol}[] PROGMEM = {{')
        lines.extend('  ' + ','.join(f'0x{byte:02x}' for byte in compressed[i:i+24]) + ',' for i in range(0, len(compressed), 24))
        lines.extend(['};', ''])
        print(f'{name}: {len(compressed)} bytes in flash')
    output = ('\n'.join(lines) + '\n').encode('ascii')
    if args.check:
        if OUTPUT.read_bytes() != output:
            raise SystemExit('Router assets need regeneration')
    else:
        OUTPUT.write_bytes(output)
    print('PASS: pinned router assets ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
