// Use the P4 RNG, not the C6/HCI callback before the NimBLE host is running.
// The stock IDF 5.5.5 P4 startup keeps the SAR entropy source enabled.
static int ofe_p4_tinycrypt_rng(uint8_t *dest, unsigned int size) {
    if (!dest) return 0;
    esp_fill_random(dest, size);
    return 1;
}

