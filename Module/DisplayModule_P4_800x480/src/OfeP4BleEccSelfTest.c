int ofe_p4_ble_ecc_self_test(void) {
    // nimble_port_init() installs an HCI RNG; replace it on every pairing start
    // and retain the P4 hardware RNG for subsequent Secure Connections keys.
    uECC_set_rng(ofe_p4_tinycrypt_rng);
    uint8_t point[64], secret[32];
    uECC_Curve curve = uECC_secp256r1();
    for (unsigned i = 0; i < 2; ++i) {
        const int base = -1010 - (int)i * 10;
        if (!uECC_compute_public_key(test_private[i], point, curve)) return base - 1;
        if (memcmp(point, test_public[i], sizeof(point))) return base - 2;
        if (uECC_valid_public_key(test_public[1-i], curve)) return base - 3;
        if (!uECC_shared_secret(test_public[1-i], test_private[i], secret, curve)) return base - 4;
        if (memcmp(secret, test_shared, sizeof(secret))) return base - 5;
    }
    return 0;
}
